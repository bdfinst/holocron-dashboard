/**
 * the style library used by default in v5 is emotion, so using
 * CacheProvider instead of StyledEngineProvider
 * see more at https://mui.com/guides/migration-v4/
 * Also, this is the suggested approach for nonce csp, so we are reading the meta
 * tag: https://github.com/mui/material-ui/issues/24156#issuecomment-752524581
 */
const cache = createCache({
  key: 'css',
  prepend: true,
  // getting the csp nonce from <meta property="csp-nonce" content="HOLOCRON_NONCE" />
  // generated by nginx
  nonce: document
    .querySelector('meta[property="csp-nonce"]')
    .getAttribute('content'),
})

const ThemeWrapper = ({ children }: { children: ReactNode }) => {
  const [mode, setMode] = useState<PaletteMode>(() => {
    const themePreference = localStorage.get<string>(localStorageConfig.THEME)
    if (themePreference === 'light' || themePreference === 'dark') {
      return themePreference
    }
    return 'dark'
  })

  const [isGrayScale, setIsGrayScale] = useState(() => {
    const isGrayscaleMode = localStorage.get<string>(
      localStorageConfig.IS_GRAYSCALE,
    )
    if (isGrayscaleMode) {
      return true
    }
    return false
  })
  const colorMode = useMemo(
    () => ({
      toggleColorMode: (modeInput: string) => {
        setMode(prevMode => {
          let nextMode = prevMode
          switch (modeInput) {
            case 'dark':
              nextMode = 'dark'
              break
            case 'light':
            case 'gray-scale':
              nextMode = 'light'
              break
            default:
              break
          }
          localStorage.set(localStorageConfig.THEME, nextMode)

          return nextMode
        })
        setIsGrayScale(prevIsGrayscale => {
          let nextIsGrayScale = prevIsGrayscale
          switch (modeInput) {
            case 'dark':
            case 'light':
              nextIsGrayScale = false
              break
            case 'gray-scale':
              nextIsGrayScale = true
              break
            default:
              break
          }
          localStorage.set(localStorageConfig.IS_GRAYSCALE, nextIsGrayScale)
          return nextIsGrayScale
        })
      },
      isGrayScale,
      colorMode: mode,
    }),
    [setMode, isGrayScale, mode],
  )
  const theme = useMemo(() => {
    if (mode === 'dark') {
      return darkTheme // eslint-disable-next-line no-else-return
    } else if (mode === 'light' && !isGrayScale) {
      return lightTheme
    } else {
      return grayScaleTheme
    }
  }, [mode, isGrayScale])

  return (
    <CacheProvider value={cache}>
      <ColorModeContext.Provider value={colorMode}>
        <ThemeProvider theme={theme}>
          <CssBaseline />
          {children}
        </ThemeProvider>
      </ColorModeContext.Provider>
    </CacheProvider>
  )
}

export default ThemeWrapper
