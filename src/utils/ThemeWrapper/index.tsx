const ColorModeContext = createContext<{
  toggleColorMode: (colorMode: string) => void
  isGrayScale: boolean
  colorMode: string
}>({
  toggleColorMode: () => {
    // empty method because of declaration
  },
  isGrayScale: false,
  colorMode: 'dark',
})

export const useColorModeContext = () => useContext(ColorModeContext)

